import AppKit
import CryptoKit
import Observation

struct ClipItem: Identifiable, Codable, Equatable {
    enum Kind: String, Codable { case text, url, image, file }

    var id = UUID()
    var kind: Kind
    /// Text or URL string, newline-separated file paths, or the stored image's file name.
    var content: String
    var fingerprint: String
    var byteCount = 0
    var date = Date()
    var favorite = false

    var title: String {
        switch kind {
        case .image:
            return "Image (\(ByteCountFormatter.string(fromByteCount: Int64(byteCount), countStyle: .file)))"
        case .file:
            let names = content.split(separator: "\n").map { ($0 as NSString).lastPathComponent }
            return names.count == 1 ? names[0] : "\(names[0]) + \(names.count - 1) more"
        case .text, .url:
            return String(content.trimmingCharacters(in: .whitespacesAndNewlines)
                .replacingOccurrences(of: "\n", with: " ").prefix(200))
        }
    }

    var typeLabel: String {
        switch kind {
        case .text: "Text"
        case .url: "URL"
        case .image: "Image"
        case .file: content.contains("\n") ? "Files" : "File"
        }
    }

    var symbol: String {
        switch kind {
        case .text: "doc.text"
        case .url: "link"
        case .image: "photo"
        case .file: "doc"
        }
    }
}

/// Clipboard history. macOS has no change notification for the pasteboard, so this polls
/// the change counter (a single cheap integer read) a little more than once a second.
@Observable
@MainActor
final class ClipboardHistory {
    private(set) var items: [ClipItem] = []

    @ObservationIgnored private var changeCount = NSPasteboard.general.changeCount
    @ObservationIgnored private var timer: Timer?
    @ObservationIgnored private let ioQueue = DispatchQueue(label: "notch.clipboard", qos: .utility)
    @ObservationIgnored private let settings: AppSettings

    static let folder: URL = {
        let support = FileManager.default.urls(for: .applicationSupportDirectory, in: .userDomainMask)[0]
        return support.appendingPathComponent("NotchApp/Clipboard", isDirectory: true)
    }()
    private static var historyFile: URL { folder.appendingPathComponent("history.json") }

    /// Password managers and similar apps mark secrets with these; never record them.
    private static let ignoredTypes: Set<String> = [
        "org.nspasteboard.ConcealedType", "org.nspasteboard.TransientType", "org.nspasteboard.AutoGeneratedType",
        "com.agilebits.onepassword", "de.petermaurer.TransientPasteboardType", "Pasteboard generator type",
    ]

    init(settings: AppSettings) {
        self.settings = settings
        try? FileManager.default.createDirectory(at: Self.folder, withIntermediateDirectories: true)
        if let data = try? Data(contentsOf: Self.historyFile),
           let saved = try? JSONDecoder().decode([ClipItem].self, from: data) {
            items = saved
        }
    }

    func start() {
        guard timer == nil else { return }
        let timer = Timer.scheduledTimer(withTimeInterval: 0.75, repeats: true) { [weak self] _ in
            MainActor.assumeIsolated { self?.poll() }
        }
        timer.tolerance = 0.25
        self.timer = timer
    }

    // MARK: Actions

    func copy(_ item: ClipItem) {
        let pasteboard = NSPasteboard.general
        pasteboard.clearContents()
        switch item.kind {
        case .text, .url:
            pasteboard.setString(item.content, forType: .string)
        case .file:
            let urls = item.content.split(separator: "\n").map { URL(fileURLWithPath: String($0)) as NSURL }
            pasteboard.writeObjects(urls)
        case .image:
            if let image = NSImage(contentsOf: Self.folder.appendingPathComponent(item.content)) {
                pasteboard.writeObjects([image])
            }
        }
        // Record our own write directly instead of re-capturing it on the next poll.
        changeCount = pasteboard.changeCount
        insert(item)
    }

    func toggleFavorite(_ item: ClipItem) {
        guard let index = items.firstIndex(where: { $0.id == item.id }) else { return }
        items[index].favorite.toggle()
        save()
    }

    func remove(_ item: ClipItem) {
        items.removeAll { $0.id == item.id }
        deleteImageIfUnused(item)
        save()
    }

    /// Clears history but keeps favorites.
    func clearHistory() {
        let removed = items.filter { !$0.favorite }
        items.removeAll { !$0.favorite }
        removed.forEach(deleteImageIfUnused)
        save()
    }

    // MARK: Capture

    private func poll() {
        let pasteboard = NSPasteboard.general
        guard pasteboard.changeCount != changeCount else { return }
        changeCount = pasteboard.changeCount
        // The counter still advances while paused, so resuming doesn't pick up what was copied meanwhile.
        guard !settings.clipboardPaused else { return }
        guard let types = pasteboard.types,
              !types.contains(where: { Self.ignoredTypes.contains($0.rawValue) }) else { return }

        // Files before text: Finder also puts the file name on the pasteboard as text.
        if types.contains(.fileURL),
           let urls = pasteboard.readObjects(forClasses: [NSURL.self], options: [.urlReadingFileURLsOnly: true]) as? [URL],
           !urls.isEmpty {
            let paths = urls.map(\.path).joined(separator: "\n")
            insert(ClipItem(kind: .file, content: paths, fingerprint: "file:" + paths))
        } else if let string = pasteboard.string(forType: .string),
                  !string.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty {
            let text = String(string.prefix(100_000))
            insert(ClipItem(kind: Self.isWebURL(text) ? .url : .text, content: text, fingerprint: "text:" + text))
        } else if let png = pasteboard.data(forType: .png) {
            captureImage(png, isPNG: true)
        } else if let tiff = pasteboard.data(forType: .tiff) {
            captureImage(tiff, isPNG: false)
        }
    }

    /// Converting, hashing and writing large screenshots happens off the main thread.
    private func captureImage(_ data: Data, isPNG: Bool) {
        let folder = Self.folder
        ioQueue.async { [weak self] in
            guard let png = isPNG ? data : NSBitmapImageRep(data: data)?.representation(using: .png, properties: [:]) else { return }
            let digest = SHA256.hash(data: png).map { String(format: "%02x", $0) }.joined()
            let name = String(digest.prefix(32)) + ".png"
            let file = folder.appendingPathComponent(name)
            if !FileManager.default.fileExists(atPath: file.path) { try? png.write(to: file) }
            DispatchQueue.main.async {
                self?.insert(ClipItem(kind: .image, content: name, fingerprint: "image:" + digest, byteCount: png.count))
            }
        }
    }

    private static func isWebURL(_ text: String) -> Bool {
        let trimmed = text.trimmingCharacters(in: .whitespacesAndNewlines)
        guard !trimmed.contains(where: \.isWhitespace), let scheme = URL(string: trimmed)?.scheme?.lowercased() else { return false }
        return scheme == "http" || scheme == "https"
    }

    private func insert(_ item: ClipItem) {
        var entry = item
        if let index = items.firstIndex(where: { $0.fingerprint == item.fingerprint }) {
            entry = items.remove(at: index)
        }
        entry.date = Date()
        items.insert(entry, at: 0)
        applyLimit()
    }

    /// Drops the oldest non-favorites beyond the history size from Settings.
    func applyLimit() {
        var kept = 0
        var evicted: [ClipItem] = []
        items.removeAll { candidate in
            guard !candidate.favorite else { return false }
            kept += 1
            if kept > settings.clipboardLimit { evicted.append(candidate); return true }
            return false
        }
        evicted.forEach(deleteImageIfUnused)
        save()
    }

    private func deleteImageIfUnused(_ item: ClipItem) {
        guard item.kind == .image, !items.contains(where: { $0.content == item.content }) else { return }
        let file = Self.folder.appendingPathComponent(item.content)
        ioQueue.async { try? FileManager.default.removeItem(at: file) }
    }

    private func save() {
        guard let data = try? JSONEncoder().encode(items) else { return }
        let file = Self.historyFile
        ioQueue.async { try? data.write(to: file, options: .atomic) }
    }
}
